// Writes data/build-order.js: the ready builds ranked by their DPS in the DPS sim (best race of each build), so the
// build picker can list them in the same order as the sim's results.
//
// The numbers come from the sim project's own results file (the one its page shows on a first visit). That file is
// not part of the vendored copy, so run this after every sync:
//   node tools/gen-build-order.js
const fs = require('fs'), path = require('path'), vm = require('vm'), { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const SIM = path.join(ROOT, '..', 'wow-forever-warlock-sim');
const source = path.join(SIM, 'data', 'default-results.js');
if (!fs.existsSync(source)) { console.error('Not found: ' + source); process.exit(1); }

const ctx = {};
ctx.window = ctx;
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(source, 'utf8'), ctx, { filename: 'default-results.js' });
const results = ctx.WL.DEFAULT_RESULTS;

const best = {};
results.results.forEach(function (r, i) {
  const key = results.keys[i];
  if (r.race === 'none') return;                       // the no-race baseline is not a character you can play
  if (!best[key] || r.dps > best[key].dps) best[key] = { key: key, dps: Math.round(r.dps * 10) / 10, race: r.race };
});
const order = Object.keys(best).map(function (k) { return best[k]; }).sort(function (a, b) { return b.dps - a.dps; });

let commit = '';
try { commit = execSync('git rev-parse --short HEAD', { cwd: SIM }).toString().trim(); } catch (e) { commit = 'unknown'; }

const file = { generated: results.generated, simCommit: commit, order: order };
const js = '// Generated by tools/gen-build-order.js - do not edit by hand. The ready builds ranked by their DPS in the DPS sim\n' +
  '// (default settings, best race of each build).\n' +
  'window.FW_BUILD_ORDER = ' + JSON.stringify(file, null, 2) + ';\n';
fs.mkdirSync(path.join(ROOT, 'data'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'data', 'build-order.js'), js);
console.log('data/build-order.js: ' + order.length + ' builds, sim commit ' + commit);
order.forEach(function (b, i) { console.log(String(i + 1).padStart(2) + '. ' + b.key.padEnd(22) + String(b.dps).padStart(6) + '  ' + b.race); });
